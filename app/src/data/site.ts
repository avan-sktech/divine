interface ServiceSchemaInput {
  name: string;
  path: string;
  description: string;
  serviceType: string | string[];
  audience?: string[];
  offerName?: string;
  areaServed?: Record<string, unknown> | string | Array<Record<string, unknown> | string>;
}

export const serviceSchema = ({
  name,
  path,
  description,
  serviceType,
  audience = [],
  offerName,
  areaServed = [
    { '@type': 'Country', name: 'Australia' },
    { '@type': 'Place', name: 'International markets' },
  ],
}: ServiceSchemaInput) => ({
  '@context': 'https://schema.org',
  '@type': 'Service',
  '@id': `${site.url}${path}#service`,
  name,
  url: `${site.url}${path}`,
  description,
  serviceType,
  provider: { '@id': `${site.url}/#organisation` },
  areaServed,
  audience: audience.map((audienceType) => ({
    '@type': 'BusinessAudience',
    audienceType,
  })),
  availableChannel: {
    '@type': 'ServiceChannel',
    serviceUrl: `${site.url}${path}`,
    servicePhone: site.phone,
  },
  ...(offerName
    ? {
        offers: {
          '@type': 'Offer',
          name: offerName,
          url: `${site.url}/contact`,
          availability: 'https://schema.org/InStock',
        },
      }
    : {}),
});
